export const dictionaries: Record<Lang, Record<Key, string>> = { en, hi };

export type Vars = Record<string, string | number>;

/** Look a word up and fill in {placeholders}. Pure, so it also works on the server and in tests. */
export function translate(lang: Lang, key: Key, vars?: Vars): string {
  const text = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** Units are stored as English words. Unknown units (typed by someone) are shown as they are. */
export function unitLabel(lang: Lang, unit: string): string {
  const key = `unit.${unit}` as Key;
  return key in dictionaries.en ? dictionaries[lang][key] : unit;
}

